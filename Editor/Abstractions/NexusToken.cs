namespace Exerussus.Nexus.Abstractions
{
    /// <summary>
    /// Семантические токены темы (НЕ конкретные цвета). Палитра отображает каждый
    /// токен в Color; окна и страницы спрашивают токен, а не литерал — поэтому
    /// смена палитры меняет вид везде разом. Лежит в Abstractions, чтобы страница
    /// могла тематизироваться через Context, не ссылаясь на сборку Theme.
    /// </summary>
    public enum NexusToken
    {
        BgHard = 0,    // самый тёмный фон (корень окна)
        BgSoft,        // панели/тулбары
        BgRaised,      // приподнятые элементы
        TextNormal,    // основной текст
        TextDim,       // вторичный/приглушённый текст
        Border,        // разделители/рамки
        Accent,        // акцент/ссылки
        Selection,     // подсветка выбранного
        Hover,         // фон элемента при наведении
        Pressed,       // фон элемента при нажатии

        Ok,            // успех/развёрнуто
        Warning,       // предупреждение
        Error,         // ошибка/faulted
        Muted,         // нейтральный бейдж (available)
        Orphan,        // осиротевшее состояние

        // --- глубина поверхностей ---
        SurfaceHover,  // ховер для BgRaised-строк/элементов списка
        Divider,       // тонкий разделитель, мягче Border (рамки карточек/контролов)

        // --- семейство акцента (для не-кнопочного акцентного UI) ---
        AccentHover,   // ярче акцента (ховер акцентных поверхностей)
        AccentPressed, // темнее акцента (нажатые/активные)
        AccentSoft,    // низкоальфовая заливка акцентом (активная вкладка, выбранная строка)
        OnAccent,      // текст/иконка поверх акцентной/сплошной статус-заливки

        // --- мягкие статус-заливки (washes), сплошные Ok/Warning/Error остаются ---
        OkSoft,        // мягкая заливка успехом
        WarningSoft,   // мягкая заливка предупреждением
        ErrorSoft,     // мягкая заливка ошибкой (напр. конфликтная строка)

        // --- доп. текст/фокус ---
        TextFaint,     // на тон ниже TextDim (мета: хэши, счётчики, подсказки)
        Focus,         // цвет рамки фокуса (поля ввода)
    }
}
