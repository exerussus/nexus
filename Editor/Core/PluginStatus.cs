namespace Exerussus.Nexus.Core
{
    /// <summary>
    /// Исход дискавери по одному плагину. Эти три состояния НЕЛЬЗЯ схлопывать
    /// (скилл): «доступна, но не развёрнута» и «осиротевшее состояние» — разные
    /// вещи и ведут себя по-разному.
    /// </summary>
    public enum PluginStatus
    {
        /// <summary>Есть манифест в Plugins И папка в State — развёрнута, активна.</summary>
        Deployed = 0,

        /// <summary>Есть манифест, нет State — доступна, но не развёрнута (норма).</summary>
        Available = 1,

        /// <summary>Есть State, манифеста нет — плагин удалён/не подтянулся;
        /// показать и предложить очистку, но НИКОГДА не удалять молча.</summary>
        OrphanedState = 2,
    }
}
