namespace Exerussus.Nexus.Abstractions
{
    /// <summary>
    /// Семантические РОЛИ action-элементов (кнопок, бейджей, подсветок) — поверх
    /// «сырых» <see cref="NexusToken"/>. Роль описывает НАМЕРЕНИЕ (главное действие,
    /// деструктив, успех…), а палитра задаёт все её цвета и состояния в одном месте.
    /// Страница оперирует ролью, не литералом и не сборкой Theme — поэтому смена
    /// палитры перекрашивает всё разом, а сочетания не копипастятся по плагинам.
    /// Токены остаются для фонов/текста/разделителей; роли — для интерактивных частей.
    /// </summary>
    public enum NexusRole
    {
        Primary = 0,   // главное действие (Apply, Confirm)
        Common,        // обычная кнопка по умолчанию
        Alarm,         // деструктив/опасное (Delete, Undeploy)
        Success,       // подтверждение/успех
        Warning,       // осторожно
        Info,          // нейтрально-информационное
        Muted,         // вторичное, приглушённое
        Ghost,         // без заливки (только контур/текст)
    }
}
